"""القسم 7 — سعر 300$ فأكثر — دخول المنطقة الصفراء أو قبل أدناها بـ 5 نقاط (أيهما أسبق)"""
NAME = '7_تنبيه_300_فاكثر'; TIER = '300$+'; LO, HI = 300, 1e12      # نطاق السعر: LO ≤ السعر < HI
NEAR = 5.0         # عدد النقاط فوق الأصفر الأدنى

def check(x, red, yl, yh):
    """يدخل حين يصير RSI داخل المنطقة الصفراء (≤ حدها الأعلى) أو قبل حدها الأدنى بـ NEAR نقاط — أيهما أسبق.
    يبقى ما دام x ≤ ذلك الحد، ويخرج حين يرتفع فوقه."""
    if yl is None: return None
    top = max(yl + NEAR, yh if yh is not None else yl)
    if x > top: return None
    label = "أصفر أدنى - اقتراب (≤5 نقاط)" if x <= yl + NEAR else "أصفر - داخل المنطقة (دخول من الأعلى)"
    return (label, round(x - yl, 2))
