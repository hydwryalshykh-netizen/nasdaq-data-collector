"""القسم 2 — سعر 5 إلى 10$ — قاع أحمر - داخل المنطقة"""
NAME = '2_تنبيه_5_الى_10'; TIER = '5-10$'; LO, HI = 5, 10      # نطاق السعر: LO ≤ السعر < HI
RED_BAND = 0.0     # «داخل المنطقة» = RSI عند القاع الأحمر أو تحته (صفر نقطة)
RED_REAL = 35.0    # الأحمر يُعتمد فقط إذا كان فعلاً قاعاً (تحت 35)؛ سهم لم ينزل تحت 35 قط ليس له أحمر حقيقي

def check(x, red, yl, yh):
    """x = RSI الحالي. يبقى السهم في القائمة ما دام x ≤ الأحمر، ويخرج حين يرتفع فوقه."""
    if red is None or red >= RED_REAL: return None
    if x <= red + RED_BAND + 1e-9: return ("قاع أحمر - داخل المنطقة", round(x - red, 2))
    return None
