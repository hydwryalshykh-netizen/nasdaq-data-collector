"""القسم 3 — سعر 10 إلى 20$ — قاع أحمر - داخل المنطقة"""
NAME = '3_تنبيه_10_الى_20'; TIER = '10-20$'; LO, HI = 10, 20      # نطاق السعر: LO ≤ السعر < HI
RED_BAND = 1.0     # «داخل منطقة القاع الأحمر» = RSI ≤ الأحمر + 1  (= تعريف «قريب جداً من القاع» في قائمتك القديمة)
RED_REAL = 35.0    # الأحمر يُعتمد فقط إذا كان فعلاً قاعاً (تحت 35)؛ سهم لم ينزل تحت 35 قط ليس له أحمر حقيقي

def check(x, red, yl, yh):
    """x = RSI الحالي. يبقى السهم في القائمة ما دام x ≤ الأحمر + RED_BAND، ويخرج حين يرتفع فوقه."""
    if red is None or red >= RED_REAL: return None
    if x <= red + RED_BAND: return ("قاع أحمر - داخل المنطقة", round(x - red, 2))
    return None
